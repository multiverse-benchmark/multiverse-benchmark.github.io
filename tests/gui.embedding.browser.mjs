import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = process.env.BASE_URL || 'http://127.0.0.1:4173/';
const output = process.env.QA_OUTPUT_DIR || path.join(root, 'artifacts/tests');
const { chromium } = process.env.PLAYWRIGHT_MODULE ? await import(process.env.PLAYWRIGHT_MODULE) : await import('playwright');
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || undefined, headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const taskId = '251f2uwadoxpbosknb4vxd58r8bxsuo9';
try {
  await page.goto(`${base}deep-dive.html#task=${taskId}`);
  await page.getByRole('tab', { name: 'Desktop GUI', exact: true }).click();
  const iframe = page.locator('iframe[title^="MultiVerse desktop:"]');
  const frame = page.frameLocator('iframe[title^="MultiVerse desktop:"]');
  await frame.locator('[data-app-id="gridwell_drive"]').click();
  await frame.locator('[data-app-window="gridwell_drive"]').waitFor();
  await page.getByRole('button', { name: 'Gold final state', exact: true }).click();
  await frame.locator('[data-app-window="gridwell_drive"]').waitFor();
  assert((await iframe.getAttribute('src')).includes('phase=final'));
  assert((await iframe.getAttribute('src')).includes('app=gridwell_drive'));
  await frame.getByRole('navigation', { name: 'Desktop snapshot phase' }).getByRole('link', { name: 'Initial', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.mv-desktop-phase button:first-child')?.getAttribute('aria-pressed') === 'true');
  await frame.locator('[data-app-window="gridwell_drive"]').waitFor();
  assert((await iframe.getAttribute('src')).includes('phase=initial'));
  await frame.getByRole('button', { name: 'Snapshot details', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await frame.getByRole('link', { name: 'Download snapshot JSON (.gz)', exact: true }).click();
  const download = await downloadPromise;
  const downloaded = await readFile(await download.path());
  const source = await readFile(path.join(root, `public/data/states/${taskId}/initial.json.gz`));
  const digest = bytes => createHash('sha256').update(bytes).digest('hex');
  assert.equal(digest(downloaded), digest(source), 'Embedded snapshot download is byte-identical to the selected source artifact');
  await frame.getByRole('button', { name: 'Close snapshot details', exact: true }).click();
  const popupPromise = page.waitForEvent('popup');
  await page.getByRole('link', { name: 'Open full screen', exact: true }).click();
  const popup = await popupPromise;
  await popup.locator('[data-app-window="gridwell_drive"]').waitFor();
  assert.equal(new URL(popup.url()).searchParams.get('phase'), 'initial');
  assert.equal(new URL(popup.url()).searchParams.get('app'), 'gridwell_drive');
  await popup.close();
  const device = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  device.on('pageerror', error => errors.push(error.message));
  await device.goto(`${base}gui/index.html?task=0udosanswla82jeqz4d2byhupkfky028&phase=initial&app=device_setting`);
  const deviceApp = device.locator('[data-app-window="device_setting"]');
  await deviceApp.getByRole('switch', { name: 'Wi-Fi', exact: true }).waitFor();
  assert.equal(await deviceApp.getByRole('switch', { name: 'Wi-Fi', exact: true }).getAttribute('aria-checked'), 'true');
  assert(await deviceApp.getByRole('switch', { name: 'Wi-Fi', exact: true }).isDisabled());
  assert((await deviceApp.getByRole('button', { name: /Mobile Network/ }).innerText()).includes('Not stored in snapshot'));
  assert.equal(await deviceApp.getByRole('switch', { name: 'NFC', exact: true }).count(), 0);
  await deviceApp.getByRole('button', { name: /Display & Brightness/ }).click();
  const brightness = deviceApp.locator('input[type="range"]');
  assert.equal(await brightness.inputValue(), '25');
  assert(await brightness.isDisabled());
  await device.goto(`${base}gui/index.html?task=e7tsuq418ea7inozy3ldfjbg6rmvj51h&phase=initial&app=device_actions`);
  const actions = device.locator('[data-app-window="device_actions"]');
  await actions.getByText('Device settings not included in this task snapshot', { exact: true }).waitFor();
  assert.equal(await actions.locator('[data-testid="volume-range"], [data-testid="brightness-range"]').count(), 0);
  const installedApps = await device.evaluate(async () => (await (await fetch('./api/services/device_actions/tools/get_installed_apps', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ params: {} }) })).json()).result.apps);
  assert.equal(installedApps.length, 8);
  await device.close();
  assert.deepEqual(errors, []);
  await mkdir(output, { recursive: true });
  await page.getByRole('dialog').screenshot({ path: path.join(output, 'desktop-embedded.png') });
  const report = { base, taskId, selectedApp: 'gridwell_drive', outerPhasePreservesApp: true, innerPhaseSyncsOuterControls: true, embeddedDownloadByteIdentical: true, fullScreenPreservesAppAndPhase: true, deviceSettingsExactBrightness25AndWifiOn: true, missingSettingsLabeledAndNoFalseToggle: true, absentDeviceSettingsBlockHidden: true, installedAppsExactCount8: true, uncaughtErrors: errors };
  await writeFile(path.join(output, 'gui-embedding-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
