"""
Shared JSON Schema traversal utilities for FD reduction.

This module provides common traversal logic for navigating complex JSON schemas
generated by Pydantic. Both the validator (fd_reduction_manager.py) and the
mutator (Scripts/FCSpec.py) use these utilities to ensure consistent behavior.

Supported patterns:
- Direct $ref references with $defs resolution
- anyOf/oneOf (Optional types, Union types)
- allOf (combined schemas)
- Array items (List[Model])
- additionalProperties (Dict[str, Model])
- Multi-type arrays (type: ["string", "null"])
- Circular references (via visited tracking)
"""

from typing import Callable, Dict, Generator, List, Optional, Set


def resolve_ref(obj: Dict, defs: Dict, visited: Optional[Set[str]] = None) -> Dict:
    """
    Resolve $ref to actual schema from $defs.

    Args:
        obj: The schema object that may contain $ref
        defs: The $defs dictionary from the root schema
        visited: Set of already visited refs (for circular reference detection)

    Returns:
        The resolved schema, or the original if no $ref present
    """
    if visited is None:
        visited = set()

    if not isinstance(obj, dict) or "$ref" not in obj:
        return obj

    ref_path = obj["$ref"]

    # Circular reference detection
    if ref_path in visited:
        return {"type": "object", "_circular": True}

    if ref_path.startswith("#/$defs/"):
        visited = visited | {ref_path}  # Create new set to avoid mutation
        def_name = ref_path.split("/")[-1]
        resolved = defs.get(def_name, {})
        # Recursively resolve in case the def also has $ref
        return resolve_ref(resolved, defs, visited)

    return obj


def get_traversable_schema(obj: Dict, defs: Dict, visited: Optional[Set[str]] = None) -> Dict:
    """
    Get a schema that can be traversed for properties.

    Unwraps complex schema patterns to expose the underlying properties.
    For validation/read-only use - returns the first matching schema.

    Args:
        obj: The schema object to traverse
        defs: The $defs dictionary from the root schema
        visited: Set of already visited refs (for circular reference detection)

    Returns:
        A schema dict with 'properties' or 'additionalProperties' exposed
    """
    if visited is None:
        visited = set()

    if not isinstance(obj, dict):
        return {}

    # First resolve any $ref
    obj = resolve_ref(obj, defs, visited)

    # Handle circular reference placeholder
    if obj.get("_circular"):
        return obj

    # Handle allOf - merge all schemas
    if "allOf" in obj:
        merged = {}
        for sub_schema in obj["allOf"]:
            resolved_sub = get_traversable_schema(sub_schema, defs, visited)
            # Merge properties
            if "properties" in resolved_sub:
                merged.setdefault("properties", {}).update(resolved_sub["properties"])
            # Merge additionalProperties (last one wins)
            if "additionalProperties" in resolved_sub:
                merged["additionalProperties"] = resolved_sub["additionalProperties"]
        return merged

    # Handle anyOf/oneOf - find the first schema with properties or traversable content
    for key in ("anyOf", "oneOf"):
        if key in obj:
            for option in obj[key]:
                if not isinstance(option, dict):
                    continue
                # Skip null type
                if option.get("type") == "null":
                    continue

                resolved_option = resolve_ref(option, defs, visited)

                # Check for $ref that resolves to something with properties
                if "properties" in resolved_option:
                    return resolved_option

                # Check for array with items
                if resolved_option.get("type") == "array" and "items" in resolved_option:
                    return get_traversable_schema(resolved_option["items"], defs, visited)

                # Check for additionalProperties (Dict types)
                if "additionalProperties" in resolved_option:
                    return resolved_option

                # Recursively check if this option leads to traversable content
                traversable = get_traversable_schema(resolved_option, defs, visited)
                if traversable.get("properties") or traversable.get("additionalProperties"):
                    return traversable

            # If no option with properties found, return empty
            return {}

    # Handle array items (List[Model])
    if obj.get("type") == "array" and "items" in obj:
        return get_traversable_schema(obj["items"], defs, visited)

    # Handle multi-type array (e.g., type: ["string", "null"])
    if isinstance(obj.get("type"), list):
        # Filter out null and continue with the object
        non_null_types = [t for t in obj["type"] if t != "null"]
        if non_null_types and "properties" in obj:
            return obj

    return obj


def iter_mutable_schemas(
    obj: Dict, defs: Dict, visited: Optional[Set[str]] = None
) -> Generator[Dict, None, None]:
    """
    Yield all schema objects that could contain the target properties.

    Unlike get_traversable_schema which returns the first match, this yields
    ALL schemas that might need mutation. This is important for:
    - anyOf/oneOf: Multiple variants may have the same field
    - $ref: The actual $defs entry needs to be mutated

    Args:
        obj: The schema object to traverse
        defs: The $defs dictionary from the root schema
        visited: Set of already visited refs (for circular reference detection)

    Yields:
        Schema dicts that have 'properties' and could be mutated
    """
    if visited is None:
        visited = set()

    if not isinstance(obj, dict):
        return

    # Handle $ref - yield the actual $defs entry (so mutations affect it)
    if "$ref" in obj:
        ref_path = obj["$ref"]
        if ref_path in visited:
            return
        if ref_path.startswith("#/$defs/"):
            visited = visited | {ref_path}
            def_name = ref_path.split("/")[-1]
            if def_name in defs:
                yield from iter_mutable_schemas(defs[def_name], defs, visited)
        return

    # Handle allOf - yield from all sub-schemas
    if "allOf" in obj:
        for sub_schema in obj["allOf"]:
            yield from iter_mutable_schemas(sub_schema, defs, visited)
        return

    # Handle anyOf/oneOf - yield from ALL non-null variants
    for key in ("anyOf", "oneOf"):
        if key in obj:
            for option in obj[key]:
                if not isinstance(option, dict):
                    continue
                if option.get("type") == "null":
                    continue
                yield from iter_mutable_schemas(option, defs, visited)
            return

    # Handle array items (List[Model])
    if obj.get("type") == "array" and "items" in obj:
        yield from iter_mutable_schemas(obj["items"], defs, visited)
        return

    # Handle multi-type array (e.g., type: ["string", "null"])
    if isinstance(obj.get("type"), list):
        non_null_types = [t for t in obj["type"] if t != "null"]
        if non_null_types and "properties" in obj:
            yield obj
            return

    # Regular object with properties - yield it
    if "properties" in obj:
        yield obj

    # For additionalProperties (Dict[str, Model]), traverse into the value schema
    # This handles cases where the path goes through a Dict's values
    if "additionalProperties" in obj and isinstance(obj["additionalProperties"], dict):
        add_props_schema = obj["additionalProperties"]
        # If additionalProperties itself has properties, yield it
        if "properties" in add_props_schema:
            yield add_props_schema
        # Also recurse in case additionalProperties has complex structure
        elif any(
            k in add_props_schema
            for k in ("$ref", "anyOf", "oneOf", "allOf", "items", "additionalProperties")
        ):
            yield from iter_mutable_schemas(add_props_schema, defs, visited)


def field_exists_in_schema(schema: Dict, field_path: str) -> bool:
    """
    Check if a field path exists in a JSON schema.

    Handles all Pydantic-generated schema patterns.

    Args:
        schema: The JSON schema dict (should have 'properties' at root or nested)
        field_path: Dot-separated field path (e.g., "user.address.city")

    Returns:
        True if the field exists in the schema
    """
    parts = field_path.split(".")
    defs = schema.get("$defs", {})

    def check_path(current: Dict, remaining_parts: List[str], visited: Set[str]) -> bool:
        if not remaining_parts:
            return True

        part = remaining_parts[0]
        rest = remaining_parts[1:]

        # Get traversable schema (read-only, first match is fine)
        current = get_traversable_schema(current, defs, visited)

        # Handle circular reference - assume field exists
        if current.get("_circular"):
            return True

        # Check in properties
        properties = current.get("properties", {})
        if part in properties:
            if not rest:
                return True
            return check_path(properties[part], rest, visited)

        # Check in additionalProperties (Dict[str, Model])
        add_props = current.get("additionalProperties")
        if add_props and isinstance(add_props, dict):
            if not rest:
                return True
            return check_path(add_props, rest, visited)

        return False

    return check_path(schema, parts, set())


def mutate_field_in_schema(
    schema: Dict,
    field_path: str,
    mutator: Callable[[Dict, str, Dict], bool],
) -> bool:
    """
    Apply a mutation to a field in a JSON schema.

    Traverses through all complex schema patterns and applies the mutator
    function at every location where the field exists.

    Args:
        schema: The JSON schema dict (will be mutated in place)
        field_path: Dot-separated field path (e.g., "user.address.city")
        mutator: Function(properties_dict, field_name, parent_schema) -> bool
                 Called when the field is found. Should return True if mutation succeeded.
                 - properties_dict: The 'properties' dict containing the field
                 - field_name: The name of the field to mutate
                 - parent_schema: The schema object containing 'properties' (for updating 'required')

    Returns:
        True if any mutation was made
    """
    parts = field_path.split(".")
    defs = schema.get("$defs", {})

    def mutate_at_path(current: Dict, remaining_parts: List[str], visited: Set[str]) -> bool:
        if not remaining_parts:
            return False

        part = remaining_parts[0]
        rest = remaining_parts[1:]

        any_mutated = False

        # Iterate through all mutable schemas at this level
        for mutable_schema in iter_mutable_schemas(current, defs, visited.copy()):
            # Check in properties
            properties = mutable_schema.get("properties", {})
            if part in properties:
                if not rest:
                    # This is the field to mutate
                    if mutator(properties, part, mutable_schema):
                        any_mutated = True
                else:
                    # Need to go deeper
                    if mutate_at_path(properties[part], rest, visited):
                        any_mutated = True

            # Check in additionalProperties (Dict[str, Model])
            add_props = mutable_schema.get("additionalProperties")
            if add_props and isinstance(add_props, dict):
                if not rest:
                    # For additionalProperties, we can't really "remove" a dynamic key
                    # but we can mutate the value schema's properties
                    # This case is less common - usually paths go deeper
                    pass
                else:
                    # Traverse into the additionalProperties value schema
                    if mutate_at_path(add_props, rest, visited):
                        any_mutated = True

        return any_mutated

    return mutate_at_path(schema, parts, set())


def remove_field_from_schema(schema: Dict, field_path: str) -> bool:
    """
    Remove a field from a JSON schema.

    Handles nested paths and complex schema patterns. Also updates the
    'required' array at the appropriate level.

    Args:
        schema: The JSON schema dict (will be mutated in place)
        field_path: Dot-separated field path (e.g., "user.password")

    Returns:
        True if the field was removed
    """

    def remover(properties: Dict, field_name: str, parent_schema: Dict) -> bool:
        if field_name not in properties:
            return False

        del properties[field_name]

        # Update required array if present
        required = parent_schema.get("required", [])
        if field_name in required:
            required.remove(field_name)
            if required:
                parent_schema["required"] = required
            else:
                parent_schema.pop("required", None)

        return True

    return mutate_field_in_schema(schema, field_path, remover)


def set_field_description(schema: Dict, field_path: str, description: str) -> bool:
    """
    Set the description of a field in a JSON schema.

    Handles nested paths and complex schema patterns.

    Args:
        schema: The JSON schema dict (will be mutated in place)
        field_path: Dot-separated field path (e.g., "user.email")
        description: The new description to set

    Returns:
        True if the description was set
    """

    def updater(properties: Dict, field_name: str, parent_schema: Dict) -> bool:
        if field_name not in properties:
            return False

        properties[field_name]["description"] = description
        return True

    return mutate_field_in_schema(schema, field_path, updater)


