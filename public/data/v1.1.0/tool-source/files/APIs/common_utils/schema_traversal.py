def field_exists_in_data(data, field_path: str) -> bool:
    """
    Check if a field path exists in runtime data (dicts/lists).

    This is the runtime counterpart to field_exists_in_schema. While
    field_exists_in_schema checks JSON schemas, this checks actual data.

    Supports:
    - Dot notation: "msg.isRead" checks data["msg"]["isRead"]
    - Arrays (List[Model]): "items.secret" checks if ANY item has "secret"
    - Dicts (Dict[str, Model]): "users.secret" checks if ANY value has "secret"
    - Mixed nesting: "groups.users.password" works through any combination

    Args:
        data: The data to check (dict, list, or primitive)
        field_path: Dot-separated field path

    Returns:
        True if the field exists anywhere in the data structure
    """
    parts = field_path.split(".")

    def check_path(current, remaining_parts: List[str]) -> bool:
        if not remaining_parts:
            return True

        part = remaining_parts[0]
        rest = remaining_parts[1:]

        if isinstance(current, dict):
            # First check if it's a direct key
            if part in current:
                return check_path(current[part], rest)
            # Otherwise, for Dict[str, Model] (additionalProperties),
            # check if ANY value contains the field path
            for value in current.values():
                if isinstance(value, (dict, list)) and check_path(value, remaining_parts):
                    return True
            return False

        elif isinstance(current, list):
            # For arrays, check if ANY element contains the field
            for item in current:
                if check_path(item, remaining_parts):
                    return True
            return False

        return False

    return check_path(data, parts)
