# Tests: AutoFieldGeneratorMixin.run_default_generators
# ---------------------------------------------------------------------------


class TestRunDefaultGenerators(unittest.TestCase):
    def test_basic_generator_runs(self):
        db = SampleDB(items={"a": InnerModel(), "b": InnerModel(), "c": InnerModel()})
        self.assertEqual(db.total, 0)
        db.run_default_generators()
        self.assertEqual(db.total, 3)

    def test_priority_ordering(self):
        db = MultiGeneratorDB()
        db.run_default_generators()
        self.assertEqual(db.execution_order, ["a", "b"])
        self.assertEqual(db.a, 42)
        self.assertEqual(db.b, 43)

    def test_no_generators(self):
        db = EmptyGeneratorDB(value=5)
        db.run_default_generators()
        self.assertEqual(db.value, 5)

    def test_non_auto_generated_fields_unchanged(self):
        db = MultiGeneratorDB(c=99)
        db.run_default_generators()
        self.assertEqual(db.c, 99)

    def test_cross_referential_access(self):
        """Generators can read sibling data on the same model instance."""
        db = MultiGeneratorDB()
        db.run_default_generators()
        self.assertEqual(db.b, db.a + 1)


# ---------------------------------------------------------------------------
# Tests: Annotation-based discovery (no decorator)
# ---------------------------------------------------------------------------


class TestAnnotationBasedDiscovery(unittest.TestCase):
    def test_method_runs_without_decorator(self):
        """Methods are discovered purely from AutoGenerated.generator_function."""
        db = SampleDB(items={"a": InnerModel(), "b": InnerModel()})
        db.run_default_generators()
        self.assertEqual(db.total, 2)

    def test_missing_method_raises(self):
        class BrokenDB(StrictBaseModel, AutoFieldGeneratorMixin):
            x: Annotated[
                int,
                AutoGenerated(
                    generator_function="_nonexistent",
                ),
            ] = Field(default=0)

        db = BrokenDB()
        with self.assertRaises(AttributeError) as ctx:
            db.run_default_generators()
        self.assertIn("_nonexistent", str(ctx.exception))

    def test_nested_model_generators_discovered(self):
        """generator_function on nested model fields is discovered via hierarchy walk."""

        class Counters(StrictBaseModel):
            value: Annotated[
                int,
                AutoGenerated(
                    generator_function="_gen_value",
                    priority=0,
                ),
            ] = 0

        class RootDB(StrictBaseModel, AutoFieldGeneratorMixin):
            counters: Counters = Field(default_factory=Counters)

            def _gen_value(self) -> None:
                setattr(self.counters, "value", 42)

        db = RootDB()
        db.run_default_generators()
        self.assertEqual(db.counters.value, 42)

    def test_same_priority_stable(self):
        class StableDB(StrictBaseModel, AutoFieldGeneratorMixin):
            a: Annotated[
                int,
                AutoGenerated(
                    generator_function="_gen_a",
                    priority=0,
                ),
            ] = 0
            b: Annotated[
                int,
                AutoGenerated(
                    generator_function="_gen_b",
                    priority=0,
                ),
            ] = 0

            def _gen_a(self) -> None:
                self.a = 1

            def _gen_b(self) -> None:
                self.b = 2

        db = StableDB()
        db.run_default_generators()
        self.assertEqual(db.a, 1)
        self.assertEqual(db.b, 2)


