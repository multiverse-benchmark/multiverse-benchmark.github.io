class MixedModel(StrictBaseModel, AutoFieldGeneratorMixin):
    """Model with both AutoGenerated and ToolkitExcluded fields."""

    name: str = Field(default="test")
    counter: Annotated[int, AutoGenerated()] = Field(default=0)
    internal_note: Annotated[str, ToolkitExcluded()] = Field(default="")
    visible_field: int = Field(default=0)


class NestedExcludedModel(StrictBaseModel):
    """Nested model with ToolkitExcluded fields."""

    value: str = Field(default="")
    secret: Annotated[str, ToolkitExcluded()] = Field(default="hidden")


class ParentWithNested(StrictBaseModel, AutoFieldGeneratorMixin):
    """Parent model containing nested model with exclusions."""

    title: str = Field(default="")
    items: Dict[str, NestedExcludedModel] = Field(default_factory=dict)
    total: Annotated[int, AutoGenerated()] = Field(default=0)


class TestToolkitExcludedAnnotation(unittest.TestCase):
    def test_toolkit_excluded_dataclass(self):
        te = ToolkitExcluded()
        self.assertIsInstance(te, ToolkitExcluded)

    def test_toolkit_excluded_is_frozen(self):
        te = ToolkitExcluded()
        with self.assertRaises(AttributeError):
            te.new_attr = "x"


class TestUnifiedExclusionBlacklist(unittest.TestCase):
    def test_includes_auto_generated_paths(self):
        paths = MixedModel.get_exclusion_blacklist_paths()
        self.assertIn("$.counter", paths)

    def test_includes_toolkit_excluded_paths(self):
        paths = MixedModel.get_exclusion_blacklist_paths()
        self.assertIn("$.internal_note", paths)

    def test_non_excluded_absent(self):
        paths = MixedModel.get_exclusion_blacklist_paths()
        path_fields = [p.split(".")[-1] for p in paths]
        self.assertNotIn("name", path_fields)
        self.assertNotIn("visible_field", path_fields)

    def test_nested_toolkit_excluded_gets_scoped_path(self):
        paths = ParentWithNested.get_exclusion_blacklist_paths()
        self.assertIn("$.items.*.secret", paths)

    def test_nested_auto_generated_at_root(self):
        paths = ParentWithNested.get_exclusion_blacklist_paths()
        self.assertIn("$.total", paths)

    def test_nested_toolkit_excluded_discovery(self):
        all_excluded = ParentWithNested.get_all_toolkit_excluded_fields()
        self.assertIn("NestedExcludedModel", all_excluded)
        self.assertEqual(all_excluded["NestedExcludedModel"], {"secret"})


