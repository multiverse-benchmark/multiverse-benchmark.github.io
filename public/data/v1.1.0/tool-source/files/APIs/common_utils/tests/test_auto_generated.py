class TestAutoGeneratedAnnotation(unittest.TestCase):
    def test_auto_generated_dataclass(self):
        ag = AutoGenerated(generator_function="_gen_counter")
        self.assertEqual(ag.generator_function, "_gen_counter")

    def test_auto_generated_default(self):
        ag = AutoGenerated()
        self.assertEqual(ag.generator_function, "")
        self.assertEqual(ag.priority, 0)

    def test_priority_field(self):
        ag = AutoGenerated(generator_function="x", priority=5)
        self.assertEqual(ag.priority, 5)

    def test_frozen(self):
        ag = AutoGenerated(generator_function="x")
        with self.assertRaises(AttributeError):
            ag.generator_function = "y"


