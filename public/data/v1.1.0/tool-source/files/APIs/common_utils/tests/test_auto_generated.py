# Tests: AutoFieldGeneratorMixin.get_auto_generated_metadata
# ---------------------------------------------------------------------------


class TestGetAutoGeneratedMetadata(unittest.TestCase):
    def test_returns_annotations_with_generator_function(self):
        metadata = SampleDB.get_auto_generated_metadata()
        funcs = {m.generator_function for m in metadata}
        self.assertIn("_generate_total", funcs)

    def test_excludes_empty_generator_function(self):
        metadata = SampleDB.get_auto_generated_metadata()
        funcs = {m.generator_function for m in metadata}
        self.assertNotIn("", funcs)

    def test_preserves_priority(self):
        metadata = MultiGeneratorDB.get_auto_generated_metadata()
        by_name = {m.generator_function: m for m in metadata}
        self.assertEqual(by_name["_gen_a"].priority, 0)
        self.assertEqual(by_name["_gen_b"].priority, 1)

    def test_deduplicates_by_function_name(self):
        class DuplicateModel(StrictBaseModel):
            x: Annotated[int, AutoGenerated(generator_function="_gen_x")] = 0
            y: Annotated[int, AutoGenerated(generator_function="_gen_x")] = 0

        class DupDB(StrictBaseModel, AutoFieldGeneratorMixin):
            inner: DuplicateModel = Field(default_factory=DuplicateModel)

            def _gen_x(self) -> None:
                pass

        metadata = DupDB.get_auto_generated_metadata()
        funcs = [m.generator_function for m in metadata]
        self.assertEqual(funcs.count("_gen_x"), 1)


