class InnerModel(StrictBaseModel):
    value: int = Field(default=0)
    computed: Annotated[int, AutoGenerated()] = Field(default=0)


class SampleDB(StrictBaseModel, AutoFieldGeneratorMixin):
    name: str = Field(default="test")
    total: Annotated[
        int,
        AutoGenerated(
            generator_function="_generate_total",
            priority=0,
        ),
    ] = Field(default=0)
    items: Dict[str, InnerModel] = Field(default_factory=dict)

    def _generate_total(self) -> None:
        self.total = len(self.items)


class MultiGeneratorDB(StrictBaseModel, AutoFieldGeneratorMixin):
    a: Annotated[
        int,
        AutoGenerated(
            generator_function="_gen_a",
            priority=0,
        ),
    ] = Field(default=0)
    b: Annotated[
        int,
        AutoGenerated(
            generator_function="_gen_b",
            priority=1,
        ),
    ] = Field(default=0)
    c: int = Field(default=0)
    execution_order: List[str] = Field(default_factory=list)

    def _gen_b(self) -> None:
        self.b = self.a + 1
        self.execution_order.append("b")

    def _gen_a(self) -> None:
        self.a = 42
        self.execution_order.append("a")


class EmptyGeneratorDB(StrictBaseModel, AutoFieldGeneratorMixin):
    value: int = Field(default=0)


class NoAutoGenDB(StrictBaseModel, AutoFieldGeneratorMixin):
    name: str = Field(default="hello")
    count: int = Field(default=0)


