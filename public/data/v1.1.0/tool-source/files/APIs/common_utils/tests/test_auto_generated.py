class ExcludedChild(ToolkitExcludedModel):
    """Model that inherits ToolkitExcludedModel."""

    data: str = Field(default="secret")


class ParentWithExcludedChild(StrictBaseModel, AutoFieldGeneratorMixin):
    """Parent that references a ToolkitExcludedModel without field annotation."""

    name: str = Field(default="test")
    child: ExcludedChild = Field(default_factory=ExcludedChild)
    children: Dict[str, ExcludedChild] = Field(default_factory=dict)
    child_list: List[ExcludedChild] = Field(default_factory=list)


class TestToolkitExcludedModelAutoDetection(unittest.TestCase):
    """Fields whose type is a ToolkitExcludedModel subclass should be
    auto-detected without requiring explicit ToolkitExcluded() annotation."""

    def test_direct_field_auto_detected(self):
        excluded = ParentWithExcludedChild.get_all_toolkit_excluded_fields()
        parent_fields = excluded.get("ParentWithExcludedChild", set())
        self.assertIn("child", parent_fields)

    def test_dict_value_auto_detected(self):
        excluded = ParentWithExcludedChild.get_all_toolkit_excluded_fields()
        parent_fields = excluded.get("ParentWithExcludedChild", set())
        self.assertIn("children", parent_fields)

    def test_list_item_auto_detected(self):
        excluded = ParentWithExcludedChild.get_all_toolkit_excluded_fields()
        parent_fields = excluded.get("ParentWithExcludedChild", set())
        self.assertIn("child_list", parent_fields)

    def test_non_excluded_field_not_detected(self):
        excluded = ParentWithExcludedChild.get_all_toolkit_excluded_fields()
        parent_fields = excluded.get("ParentWithExcludedChild", set())
        self.assertNotIn("name", parent_fields)

    def test_blacklist_includes_auto_detected_fields(self):
        paths = ParentWithExcludedChild.get_exclusion_blacklist_paths()
        self.assertIn("$.child", paths)
        self.assertIn("$.children", paths)
        self.assertIn("$.child_list", paths)


