class TestGeneratorValidatedAssignment(unittest.TestCase):
    """Verify that generators writing via normal assignment get Pydantic
    validation (validate_assignment=True on StrictBaseModel)."""

    def test_invalid_type_raises_validation_error(self):
        """A generator writing a string to an int field should fail."""

        class BadGenDB(StrictBaseModel, AutoFieldGeneratorMixin):
            counter: Annotated[
                int,
                AutoGenerated(
                    generator_function="_gen_counter",
                ),
            ] = 0

            def _gen_counter(self) -> None:
                self.counter = "not_a_number"  # type: ignore[assignment]

        db = BadGenDB()
        with self.assertRaises(ValidationError):
            db.run_default_generators()

    def test_valid_assignment_succeeds(self):
        class GoodGenDB(StrictBaseModel, AutoFieldGeneratorMixin):
            counter: Annotated[
                int,
                AutoGenerated(
                    generator_function="_gen_counter",
                ),
            ] = 0

            def _gen_counter(self) -> None:
                self.counter = 42

        db = GoodGenDB()
        db.run_default_generators()
        self.assertEqual(db.counter, 42)

    def test_negative_on_ge0_field_raises(self):
        """A ge=0 constraint should be enforced by validated assignment."""

        class GeDB(StrictBaseModel, AutoFieldGeneratorMixin):
            count: Annotated[
                Optional[int],
                AutoGenerated(
                    generator_function="_gen_count",
                ),
            ] = Field(0, ge=0)

            def _gen_count(self) -> None:
                self.count = -1

        db = GeDB()
        with self.assertRaises(ValidationError):
            db.run_default_generators()


