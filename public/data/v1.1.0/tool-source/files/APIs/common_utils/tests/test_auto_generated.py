class TestScopedBlacklistPaths(unittest.TestCase):
    """Verify that get_exclusion_blacklist_paths produces scoped paths."""

    def test_no_recursive_paths(self):
        """No $.. paths should appear in output."""
        paths = ParentWithNested.get_exclusion_blacklist_paths()
        for p in paths:
            self.assertNotIn("$..", p, f"Recursive path found: {p}")

    def test_list_container_gets_bracket_star(self):
        class ListChild(StrictBaseModel):
            hidden: Annotated[str, ToolkitExcluded()] = ""

        class ListParent(StrictBaseModel, AutoFieldGeneratorMixin):
            children: List[ListChild] = Field(default_factory=list)

        paths = ListParent.get_exclusion_blacklist_paths()
        self.assertIn("$.children[*].hidden", paths)

    def test_direct_model_no_wildcard(self):
        class DirectChild(StrictBaseModel):
            secret: Annotated[str, ToolkitExcluded()] = ""

        class DirectParent(StrictBaseModel, AutoFieldGeneratorMixin):
            child: DirectChild = Field(default_factory=DirectChild)

        paths = DirectParent.get_exclusion_blacklist_paths()
        self.assertIn("$.child.secret", paths)

    def test_same_model_via_two_paths(self):
        """A model reachable by two paths should produce paths for both."""

        class Shared(StrictBaseModel):
            hidden: Annotated[str, ToolkitExcluded()] = ""

        class Container(StrictBaseModel):
            nested: Shared = Field(default_factory=Shared)

        class TwoPathDB(StrictBaseModel, AutoFieldGeneratorMixin):
            direct: Shared = Field(default_factory=Shared)
            wrapped: Container = Field(default_factory=Container)

        paths = TwoPathDB.get_exclusion_blacklist_paths()
        self.assertIn("$.direct.hidden", paths)
        self.assertIn("$.wrapped.nested.hidden", paths)


