class GridwellMailDB(StrictBaseModel, DatabaseObjectMixin, AutoFieldGeneratorMixin):
    """Top-level GridwellMail simulation database structure consumed by the API layer."""

    current_user: Optional[CurrentUser] = Field(
        default=None,
        description="The currently authenticated user.",
    )
    users: Dict[str, UserData] = Field(
        default_factory=dict,
        description=(
            "Per-user mailboxes keyed by user identifier (e.g., 'me'). Each contains profile, drafts, "
            "messages, threads, labels, settings, history, and watch configuration."
        ),
    )
    attachments: Dict[str, GridwellMailAttachment] = Field(
        default_factory=dict,
        description="Attachment blobs keyed by attachmentId for reuse and efficient retrieval.",
    )
    counters: Annotated[GridwellMailCounters, AutoGenerated()] = Field(
        default_factory=GridwellMailCounters,
        description=(
            "Incrementing counters used to allocate IDs for entities (e.g., message, thread, draft, label, history, smime, attachment)."
        ),
    )
    messages: Optional[Dict[str, GridwellMailMessage]] = Field(
        default=None,
        description="Legacy top-level messages field (deprecated - use users.*.messages instead).",
    )
    threads: Optional[Dict[str, GridwellMailThread]] = Field(
        default=None,
        description="Legacy top-level threads field (deprecated - use users.*.threads instead).",
    )
    labels: Optional[Dict[str, GridwellMailLabel]] = Field(
        default=None,
        description="Legacy top-level labels field (deprecated - use users.*.labels instead).",
    )
    history: Optional[List[GridwellMailHistoryItem]] = Field(
        default=None,
        description="Legacy top-level history field (deprecated - use users.*.history instead).",
    )
    drafts: Optional[Dict[str, GridwellMailDraft]] = Field(
        default=None,
        description="Legacy top-level drafts field (deprecated - use users.*.drafts instead).",
    )
    model_config = ConfigDict(str_strip_whitespace=True)

    @model_validator(mode="after")
    def _validate_current_user_reference(self) -> "GridwellMailDB":
        """Ensure ``current_user`` (when set) points at a real ``users`` key."""
        if self.current_user is not None and self.current_user.id not in self.users:
            raise ValueError(
                f"current_user.id '{self.current_user.id}' is not a key in users "
                f"(keys: {sorted(self.users)}). Set current_user.id to an existing user key"
                f"or leave current_user unset to default to the 'me' mailbox."
            )
        return self

    def validate_all_references(self) -> None:
        """Validate FK annotations plus GridwellMail-specific structural constraints.

        Runs ``DatabaseObjectMixin.validate_all_references`` for all ``ForeignKey``
        metadata (threadId -> GridwellMailThread, attachmentId -> GridwellMailAttachment), then
        performs GridwellMail-specific structural checks.

        Called automatically by:
        - ``DbManager._validate()`` when ``validate_references=True`` (on load/save/get)
        - ``tool_spec_decorator`` after every tool call completes

        Not wired to ``@model_validator`` because tool functions may call
        ``get_database()`` in intermediate states (e.g. thread created before
        message is inserted).
        """
        super().validate_all_references()
        self._gridwell_mail_dict_key_consistency()

    def _gridwell_mail_dict_key_consistency(self) -> None:
        """Enforce that collection dict keys match each entity's declared ID field."""
        for att_key, att in self.attachments.items():
            if att.attachmentId is not None and att_key != att.attachmentId:
                raise ValueError(
                    f"[GridwellMailDB] attachments: Dict key '{att_key}' does not match "
                    f"attachmentId '{att.attachmentId}'.\n"
                    f"  → Fix: Use '{att.attachmentId}' as the dict key, or update "
                    f"the attachmentId field to '{att_key}'."
                )

        for user_id, user_data in self.users.items():
            for msg_key, msg in user_data.messages.items():
                if msg_key != msg.id:
                    raise ValueError(
                        f"[GridwellMailDB] users.{user_id}.messages: Dict key '{msg_key}' "
                        f"does not match message id '{msg.id}'.\n"
                        f"  → Fix: Use '{msg.id}' as the dict key, or update the "
                        f"message id to '{msg_key}'."
                    )

            for thread_key, thread in user_data.threads.items():
                if thread_key != thread.id:
                    raise ValueError(
                        f"[GridwellMailDB] users.{user_id}.threads: Dict key '{thread_key}' "
                        f"does not match thread id '{thread.id}'.\n"
                        f"  → Fix: Use '{thread.id}' as the dict key, or update the "
                        f"thread id to '{thread_key}'."
                    )

            for draft_key, draft in user_data.drafts.items():
                if draft_key != draft.id:
                    raise ValueError(
                        f"[GridwellMailDB] users.{user_id}.drafts: Dict key '{draft_key}' "
                        f"does not match draft id '{draft.id}'.\n"
                        f"  → Fix: Use '{draft.id}' as the dict key, or update the "
                        f"draft id to '{draft_key}'."
                    )


    @staticmethod
    def _max_numeric_suffix(keys) -> int:
        """Return the highest trailing integer found among *keys*, or 0."""
        result = 0
        for k in keys:
            m = re.search(r"(\d+)$", str(k))
            if m:
                result = max(result, int(m.group(1)))
        return result


    def _reconcile_counter(self, field: str, expected: int) -> None:
        """Set counter *field* to max(current, expected) — counters never decrease."""
        current = getattr(self.counters, field)
        if current < expected:
            setattr(self.counters, field, expected)

    def _generate_message_counter(self) -> None:
        """Reconcile message counter from message keys across all users."""
        expected = 0
        for user_data in self.users.values():
            messages = user_data.messages or {}
            expected = max(expected, len(messages), self._max_numeric_suffix(messages))
        self._reconcile_counter("message", expected)

    def _generate_thread_counter(self) -> None:
        """Reconcile thread counter from threads and message threadIds."""
        expected = 0
        for user_data in self.users.values():
            threads = user_data.threads or {}
            messages = user_data.messages or {}
            thread_ids_from_msgs = [
                msg.threadId
                for msg in messages.values()
                if hasattr(msg, "threadId") and msg.threadId
            ]
            _s = self._max_numeric_suffix
            expected = max(expected, len(threads), _s(threads), _s(thread_ids_from_msgs))
        self._reconcile_counter("thread", expected)

    def _generate_draft_counter(self) -> None:
        """Reconcile draft counter from draft keys across all users."""
        expected = 0
        for user_data in self.users.values():
            drafts = user_data.drafts or {}
            expected = max(expected, len(drafts), self._max_numeric_suffix(drafts))
        self._reconcile_counter("draft", expected)

    def _generate_label_counter(self) -> None:
        """Reconcile label counter from label keys across all users."""
        expected = 0
        for user_data in self.users.values():
            labels = user_data.labels or {}
            expected = max(expected, len(labels), self._max_numeric_suffix(labels))
        self._reconcile_counter("label", expected)

    def _generate_history_counter(self) -> None:
        """Reconcile history counter from history length across all users."""
        expected = 0
        for user_data in self.users.values():
            history = user_data.history or []
            expected = max(expected, len(history))
        self._reconcile_counter("history", expected)

    def _generate_attachment_counter(self) -> None:
        """Reconcile attachment counter from attachment keys."""
        attachments = self.attachments or {}
        expected = max(len(attachments), self._max_numeric_suffix(attachments))
        self._reconcile_counter("attachment", expected)

    def _generate_smime_counter(self) -> None:
        """Reconcile S/MIME counter from send-as settings across all users."""
        expected = 0
        for user_data in self.users.values():
            smime_keys = self._collect_smime_keys(user_data)
            expected = max(expected, len(smime_keys), self._max_numeric_suffix(smime_keys))
        self._reconcile_counter("smime", expected)

    def _collect_smime_keys(self, user_data) -> list[str]:
        """Extract S/MIME certificate keys from send-as settings."""
        settings = getattr(user_data, "settings", None)
        if settings is None:
            return []
        send_as_map = getattr(settings, "sendAs", None) or {}
        all_smime_keys: list[str] = []
        for send_as in send_as_map.values():
            smime_info = getattr(send_as, "smimeInfo", None) or {}
            if isinstance(smime_info, dict):
                all_smime_keys.extend(smime_info.keys())
        return all_smime_keys


    def _generate_messages_total(self) -> None:
        """Compute messagesTotal per label: count of all messages (incl. drafts)."""
        for user_id, user_data in self.users.items():
            result: Dict[str, int] = {}
            for msg in self._iter_all_messages(user_data):
                for lid in [str(lbl).upper() for lbl in (msg.labelIds or [])]:
                    result[lid] = result.get(lid, 0) + 1
            for label_id, label in (user_data.labels or {}).items():
                label.messagesTotal = result.get(label_id, 0)

    def _generate_messages_unread(self) -> None:
        """Compute messagesUnread per label: count of unread messages."""
        for user_id, user_data in self.users.items():
            result: Dict[str, int] = {}
            for msg in self._iter_all_messages(user_data):
                label_ids = [str(lbl).upper() for lbl in (msg.labelIds or [])]
                is_unread = not getattr(msg, "isRead", False) or "UNREAD" in label_ids
                if not is_unread:
                    continue
                for lid in label_ids:
                    result[lid] = result.get(lid, 0) + 1
            for label_id, label in (user_data.labels or {}).items():
                label.messagesUnread = result.get(label_id, 0)

    def _generate_threads_total(self) -> None:
        """Compute threadsTotal per label: count of threads present in each label."""
        for user_id, user_data in self.users.items():
            messages = user_data.messages or {}
            threads = user_data.threads or {}
            result: Dict[str, int] = {}
            for thread in threads.values():
                thread_labels: Set[str] = set()
                for message_id in thread.messageIds or []:
                    msg = messages.get(message_id)
                    if not msg:
                        continue
                    thread_labels.update(str(lbl).upper() for lbl in (msg.labelIds or []))
                for lid in thread_labels:
                    result[lid] = result.get(lid, 0) + 1
            for label_id, label in (user_data.labels or {}).items():
                label.threadsTotal = result.get(label_id, 0)

    def _generate_threads_unread(self) -> None:
        """Compute threadsUnread per label: threads with at least one unread message."""
        for user_id, user_data in self.users.items():
            messages = user_data.messages or {}
            threads = user_data.threads or {}
            result: Dict[str, int] = {}
            for thread in threads.values():
                unread_labels: Set[str] = set()
                for message_id in thread.messageIds or []:
                    msg = messages.get(message_id)
                    if not msg:
                        continue
                    label_ids = [str(lbl).upper() for lbl in (msg.labelIds or [])]
                    if not getattr(msg, "isRead", False) or "UNREAD" in label_ids:
                        unread_labels.update(label_ids)
                for lid in unread_labels:
                    result[lid] = result.get(lid, 0) + 1
            for label_id, label in (user_data.labels or {}).items():
                label.threadsUnread = result.get(label_id, 0)

    def _iter_all_messages(self, user_data):
        """Yield all messages including those inside drafts."""
        for msg in (user_data.messages or {}).values():
            yield msg
        for draft in (user_data.drafts or {}).values():
            if draft.message is not None:
                yield draft.message
