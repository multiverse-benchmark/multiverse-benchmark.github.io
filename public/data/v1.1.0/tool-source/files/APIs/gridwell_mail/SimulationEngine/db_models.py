    @model_validator(mode="before")
    @classmethod
    def _pre_normalize(
        cls, data: Union[ModelValidatorData, None]
    ) -> Union[ModelValidatorData, None]:
        """Pre-validation: fix structural issues that would fail field parsing."""
        if isinstance(data, dict):
            data = copy.deepcopy(data)
            if "labelIds" not in data or data["labelIds"] is None:
                data["labelIds"] = []

            # Payload parts: Pydantic expects a dict for MessagePartBody,
            # so coerce None / missing body inside parts before field
            # validators run.
            if "payload" in data and data["payload"] is not None:
                payload = data["payload"]
                if (
                    isinstance(payload, dict)
                    and "parts" in payload
                    and isinstance(payload["parts"], list)
                ):
                    for part in payload["parts"]:
                        if isinstance(part, dict):
                            if part.get("body") is None:
                                part["body"] = {}
        return data

    @model_validator(mode="after")
    def _post_normalize(self) -> "GridwellMailMessage":
        """Post-validation normalization.

        At this point every field is populated (with its default if the key
        was missing from the input). Normalize Optional[str] fields so
        downstream code never sees None for string content, and sync isRead
        with the UNREAD label.
        """
        # Normalize Optional[str] fields: None -> "".
        # threadId is excluded because None is valid (drafts without a thread).
        # internalDate uses "0" instead of "" so int()/float() parsing stays safe.
        _skip_str = {"threadId", "internalDate"}
        for name, field_info in self.__class__.model_fields.items():
            if name in _skip_str:
                continue
            annotation = field_info.annotation
            is_optional_str = annotation is Optional[str] or (
                getattr(annotation, "__origin__", None) is Union
                and str in getattr(annotation, "__args__", ())
                and type(None) in getattr(annotation, "__args__", ())
                and len(getattr(annotation, "__args__", ())) == 2
            )
            if is_optional_str and getattr(self, name) is None:
                object.__setattr__(self, name, "")

        if self.internalDate is None or self.internalDate == "":
            object.__setattr__(self, "internalDate", "0")

        # Uppercase system labels, preserve user label case
        label_ids = set()
        for label in self.labelIds:
            if label.upper() in GRIDWELL_MAIL_SYSTEM_LABELS:
                label_ids.add(label.upper())
            else:
                label_ids.add(label)

        # Sync isRead with UNREAD label
        if self.isRead is not None:
            if self.isRead is True:
                label_ids.discard("UNREAD")
            else:
                label_ids.add("UNREAD")
            is_read = self.isRead
        else:
            is_read = "UNREAD" not in label_ids

        object.__setattr__(self, "labelIds", sorted(list(label_ids)))
        object.__setattr__(self, "isRead", is_read)

        return self

